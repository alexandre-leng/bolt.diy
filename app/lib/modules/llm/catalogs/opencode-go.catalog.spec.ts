import { describe, expect, it } from 'vitest';
import { CATALOG_GENERATED_AT, OPENCODE_GO_CATALOG, catalogProtocol, catalogThinkingOnly } from './opencode-go.catalog';

/*
 * The catalog is generated from models.dev (see scripts/generate-model-catalog.mjs). These tests
 * guard the two ways it can go wrong: an entry with impossible limits, and a model the agent loop
 * cannot use (no tool calls, deprecated).
 */
describe('OpenCode Go catalog', () => {
  it('carries the real limits instead of the old flat 128k/8k', () => {
    const flash = OPENCODE_GO_CATALOG.find((entry) => entry.id === 'deepseek-v4.1-flash');

    expect(flash).toBeDefined();

    // models.dev: 1,000,000 context / 384,000 output. The hand-written list said 128000/8192.
    expect(flash!.context).toBeGreaterThanOrEqual(1_000_000);
    expect(flash!.maxOutput).toBeGreaterThanOrEqual(384_000);
  });

  it('offers every model the gateway answers, with usable limits', () => {
    const ids = OPENCODE_GO_CATALOG.map((entry) => entry.id);

    for (const id of ['deepseek-v4.1-flash', 'deepseek-v4-pro', 'glm-5.2', 'kimi-k2.7-code', 'mimo-v2.6-pro']) {
      expect(ids).toContain(id);
    }

    expect(OPENCODE_GO_CATALOG.length).toBeGreaterThanOrEqual(30);
  });

  it('has no duplicate id and no impossible value', () => {
    const ids = OPENCODE_GO_CATALOG.map((entry) => entry.id);

    expect(new Set(ids).size).toBe(ids.length);

    for (const entry of OPENCODE_GO_CATALOG) {
      expect(entry.context, entry.id).toBeGreaterThan(0);
      expect(entry.maxOutput, entry.id).toBeGreaterThan(0);
      expect(entry.maxOutput, entry.id).toBeLessThanOrEqual(entry.context);
      expect(['chat', 'responses', 'messages'], entry.id).toContain(entry.protocol);
      expect(entry.label.length, entry.id).toBeGreaterThan(0);
    }
  });

  it('routes each model to the protocol the gateway speaks, and keeps the id pattern as fallback', () => {
    expect(catalogProtocol('claude-haiku-5-5')).toBe('messages');
    expect(catalogProtocol('gpt-6-luna')).toBe('responses');
    expect(catalogProtocol('grok-4.7')).toBe('responses');
    expect(catalogProtocol('deepseek-v4.1-flash')).toBe('chat');

    // Unknown ids keep working through the pattern.
    expect(catalogProtocol('claude-something-new')).toBe('messages');
    expect(catalogProtocol('gpt-something-new')).toBe('responses');
    expect(catalogProtocol('glm-something-new')).toBe('chat');
  });

  it('marks the models that refuse `thinking: disabled`', () => {
    // Measured live: glm-5.3 answers 400 "is a thinking-only model; disabling ... is not supported".
    expect(catalogThinkingOnly('glm-5.3')).toBe(true);
    expect(catalogThinkingOnly('deepseek-v4.1-flash')).toBe(false);
    expect(catalogThinkingOnly('unknown-model')).toBe(false);
  });

  it('was generated by the script, and says when', () => {
    // A missing date means someone edited the file by hand instead of running the generator.
    expect(CATALOG_GENERATED_AT).toMatch(/^\d{4}-\d{2}-\d{2}$/);
  });
});
